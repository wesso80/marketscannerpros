import type { CountryCode, RawCalendarInput, TimingStatus } from './types';

/**
 * Curated global schedule seed (fallback provider `curated`).
 *
 * Timing semantics:
 *   CONFIRMED  — date AND time from a published official calendar (central-bank
 *                meeting schedules, BLS/BEA release schedules). sourceAuthority=OFFICIAL.
 *   TENTATIVE  — date official, time not fixed by the institution (BoJ). OFFICIAL.
 *   ESTIMATED  — typical-pattern estimate; must be verified. sourceAuthority=CURATED.
 *
 * Times are the issuing country's local wall-clock; conversion to UTC happens
 * in normalize.ts through the tz database so DST is never hand-coded here.
 *
 * Reference periods are written short ("Aug", "Q3"); normalize.ts resolves the
 * year from the release date ("Aug 2026", "Q4 2026").
 *
 * Curated rows never carry actual/consensus — those come from live providers only.
 */

const ESTIMATE_NOTE = 'Estimated from typical release pattern; verify against official calendar.';

function ev(
  canonicalIndicatorId: string,
  localDate: string,
  localTime: string,
  referencePeriod: string | null,
  timing: TimingStatus = 'ESTIMATED',
  timingNote?: string,
): RawCalendarInput {
  const countryCode = canonicalIndicatorId.slice(0, 2) as CountryCode;
  const official = timing === 'CONFIRMED' || timing === 'TENTATIVE';
  return {
    providerId: 'curated',
    countryCode,
    canonicalIndicatorId,
    localDate,
    localTime,
    referencePeriod,
    timingStatus: timing,
    sourceAuthority: official ? 'OFFICIAL' : 'CURATED',
    providerStatus: 'FALLBACK',
    timingNote: timingNote ?? (timing === 'ESTIMATED' ? ESTIMATE_NOTE : null),
  };
}

